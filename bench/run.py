#!/usr/bin/env python3
"""Run the Unio benchmarks against equivalent programs in other languages.

Usage:
    python3 bench/run.py [--runs N] [--only NAME,...] [--json FILE] [--check-floor] [--unio PATH]
                         [--native] [--check-go] [--check-startup] [--check-free]
                         [--check-compile] [--check-copies]

With --native, each Unio program is also built with `unio build --release` and runs as a native
executable ("Unio native"); the ratios and the floor then refer to the native executable.
The benchmark "empty" measures the start of an empty program: the median of STARTUP_RUNS runs,
and with --check-startup the native executable must start within 5 ms (requirement 7.1).
The benchmark "free" measures the pause of freeing a large structure at once (RFC 0007).
The benchmark "package" measures `unio check` and a full `unio build --release` of a generated
package of 10,000 lines (requirement 7.1: at most 1 s and 30 s; --check-compile gates them).
The benchmark "copies" measures the cost of copies of values (requirement L-11b; --check-copies
gates the changes that must not copy what they do not change).

The rules of the comparison are in bench/README.md. Only the Python standard library is used.
"""

import argparse
import json
import os
import platform
import random
import shutil
import statistics
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BENCH = ROOT / "bench"
DATA = BENCH / "data"
BUILD = BENCH / "build"

# Requirement 7.1: text and JSON processing at least 0.5x of CPython 3.13, that is,
# Unio may take at most twice the time of Python. The benchmarks this floor applies to:
FLOOR = 0.5
FLOOR_BENCHMARKS = ("wc", "json", "text", "loop")

# RFC 0003: native executables take at most twice the time of the same algorithm in Go;
# the target is parity. Gated for release 0.1: wc and loop; for 0.2: every benchmark.
GO_LIMIT = 2.0
GO_GATED = ("wc", "loop")
# Peak resident memory: at most twice Go's peak plus 8 MB for the runtime, on the same gate.
GO_MEMORY_ALLOWANCE = 8_000_000

# Requirement 7.1: the start of an empty program at most 5 ms. A start takes a few milliseconds,
# so one run is noise: the median of many runs is compared, and the spread is recorded.
STARTUP_LIMIT = 0.005
STARTUP_RUNS = 101

# Plan section 12, condition 3, and RFC 0007: the latency of freeing a large structure at once,
# the counterpart of a GC pause under reference counting. "wide" is about 100 MB of typical
# values (records with texts, a list of texts and a map, a map by name); "deep" is a chain of
# nested values, freed without recursion since RFC 0007. The pause is the time between the two
# lines the program prints around the drop; the median of the runs is reported. RFC 0007
# replaced the 7.1 row "GC pause at a 100 MB heap at most 10 ms" (FREE_LIMIT, printed for
# comparison) with a bound per MB: with --check-free the median wide pause must stay within
# FREE_LIMIT_PER_MB per MB of peak memory.
FREE_CASES = (("wide", 40_000), ("deep", 1_000_000))
FREE_RUNS = 7
FREE_LIMIT = 0.010
FREE_LIMIT_PER_MB = 0.001

# Requirement 7.1: `unio check` of a 10,000-line package at most 1 s, and a full `--release`
# build of it at most 30 s. The package is generated by bench/package/generate.py into
# bench/data/package/; a full build starts without the cache of the package (target/), which is
# removed before every run. The median of the runs is compared with the limit.
PACKAGE_LINES = 10_000
CHECK_LIMIT = 1.0
BUILD_LIMIT = 30.0
PACKAGE_RUNS = 5

# Requirement L-11b: values are shared until changed; a change copies only the changed level,
# a change of an unshared value happens in place, and appending to an unshared list takes
# amortized constant time. Each case of bench/copies/ runs at a scale and at ten times the
# scale; the cost of one change is its time divided by the number of changes. For the cases
# "in place" and "one level" the cost of a change must not grow with the size of what is not
# changed: with --check-copies the cost at ten times the size is at most COPY_GROWTH_LIMIT
# times the cost at the size (a copy of the unchanged part would make it about 10). The cases
# "copy" copy the whole level by design; their cost per element copied is recorded.
# (name, kind, (size, changes) at the scale, (size, changes) at ten times the scale)
COPY_CASES = (
    ("append", "in place", (0, 200_000), (0, 2_000_000)),
    ("list_in_place", "in place", (10_000, 1_000_000), (100_000, 1_000_000)),
    ("list_var_parameter", "in place", (10_000, 1_000_000), (100_000, 1_000_000)),
    ("map_in_place", "in place", (10_000, 1_000_000), (100_000, 1_000_000)),
    ("struct_field", "one level", (10_000, 1_000_000), (100_000, 1_000_000)),
    ("nested_row", "one level", (10_000, 200_000), (100_000, 200_000)),
    ("list_copy", "copy", (10_000, 2_000), (100_000, 200)),
    ("map_copy", "copy", (10_000, 200), (100_000, 20)),
    ("list_by_value", "copy", (10_000, 2_000), (100_000, 200)),
)
COPY_RUNS = 5
COPY_GROWTH_LIMIT = 3.0

VOCABULARY = (
    "the quick brown fox jumps over lazy dog and then runs into forest where "
    "unio values text list map option result error test module function return "
    "мир текст слово данные строка поток файл время"
).split()


def generate_text(path, size, seed):
    """Lines of 4 to 16 words separated by single spaces; ASCII and Cyrillic; no empty lines."""
    rng = random.Random(seed)
    lines = []
    written = 0
    while written < size:
        line = " ".join(rng.choice(VOCABULARY) for _ in range(rng.randint(4, 16)))
        lines.append(line)
        written += len(line.encode()) + 1
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def generate_json(path, size, seed):
    """An array of records with integers, texts with escapes, booleans, null, and nesting."""
    rng = random.Random(seed)
    records = []
    written = 0
    while written < size:
        record = {
            "id": len(records),
            "name": " ".join(rng.choice(VOCABULARY) for _ in range(rng.randint(1, 4))),
            "note": rng.choice(["plain", "with \"quotes\"", "tab\there", "line\nbreak", "back\\slash"]),
            "score": rng.randint(-1000000, 1000000),
            "active": rng.random() < 0.5,
            "parent": None if rng.random() < 0.3 else rng.randint(0, 1000),
            "tags": [rng.choice(VOCABULARY) for _ in range(rng.randint(0, 5))],
            "point": {"x": rng.randint(-500, 500), "y": rng.randint(-500, 500)},
        }
        records.append(record)
        written += len(json.dumps(record, ensure_ascii=False, separators=(", ", ": "))) + 3
    path.write_text(json.dumps(records, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


def ensure_data():
    DATA.mkdir(exist_ok=True)
    files = {
        "wc": (DATA / "text-20mb.txt", lambda p: generate_text(p, 20_000_000, 1)),
        "text": (DATA / "text-4mb.txt", lambda p: generate_text(p, 4_000_000, 2)),
        # A .txt name, so that the documentation checkers, which read every .json file of the
        # checkout, do not read the generated document.
        "json": (DATA / "json-10mb.txt", lambda p: generate_json(p, 10_000_000, 3)),
    }
    for _, (path, make) in files.items():
        if not path.exists():
            print(f"generating {path.relative_to(ROOT)}", file=sys.stderr)
            make(path)
    return {name: str(path) for name, (path, _) in files.items()}


def version(command):
    try:
        out = subprocess.run(command, capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired):
        return None
    # The JVM prints "Picked up JAVA_TOOL_OPTIONS: ..." before its version when that is set.
    lines = [line.strip() for line in (out.stdout + out.stderr).splitlines()
             if line.strip() and not line.startswith("Picked up ")]
    return lines[0] if lines else None


def find_unio(explicit):
    candidates = [explicit] if explicit else [
        ROOT / "compiler" / "target" / "release" / "unio",
        ROOT / "compiler" / "target" / "release" / "unio.exe",
    ]
    for candidate in candidates:
        if candidate and Path(candidate).exists():
            return str(candidate)
    return None


class Languages:
    """How to build and run each language; a language whose tools are missing is skipped."""

    def __init__(self, unio, native=False):
        self.unio = unio
        self.native = native
        self.python = sys.executable
        self.versions = {}
        self.missing = {}
        self.versions["Unio"] = ("unio interpreter, commit " + (version(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"]) or "?")) if unio else None
        self.versions["Python"] = f"Python {platform.python_version()}"
        for name, tool, args in (
            ("Ruby", "ruby", ["--version"]),
            ("JavaScript", "node", ["--version"]),
            ("Go", "go", ["version"]),
            ("Java", "java", ["-version"]),
            ("Rust", "rustc", ["--version"]),
        ):
            path = shutil.which(tool)
            if path is None or (name == "Java" and shutil.which("javac") is None):
                self.missing[name] = f"{tool} not found"
                continue
            self.versions[name] = version([path] + args)
            if name == "JavaScript":
                self.versions[name] = "Node.js " + (self.versions[name] or "")
        if unio is None:
            self.missing["Unio"] = "build compiler/ with cargo build --release first"
        if native:
            if unio is None:
                self.missing["Unio native"] = "build compiler/ with cargo build --release first"
            else:
                self.versions["Unio native"] = "unio build --release, commit " + (
                    version(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"]) or "?")

    def command(self, language, source, data):
        """The command that runs the program, after building it outside the measurement."""
        source = Path(source)
        args = [data] if data else []
        if language == "Unio":
            return [self.unio, "run", str(source), "--"] + args if args else [self.unio, "run", str(source)]
        if language == "Unio native":
            BUILD.mkdir(exist_ok=True)
            binary = BUILD / (source.stem + "-unio")
            subprocess.run([self.unio, "build", "--release", str(source), "-o", str(binary)],
                           check=True)
            return [str(binary)] + args
        if language == "Python":
            return [self.python, str(source)] + args
        if language == "Ruby":
            return ["ruby", str(source)] + args
        if language == "JavaScript":
            return ["node", str(source)] + args
        BUILD.mkdir(exist_ok=True)
        if language == "Go":
            binary = BUILD / (source.stem + "-go")
            subprocess.run(["go", "build", "-o", str(binary), str(source)], check=True,
                           env=dict(os.environ, GO111MODULE="off"))
            return [str(binary)] + args
        if language == "Rust":
            binary = BUILD / (source.stem + "-rs")
            subprocess.run(["rustc", "-C", "opt-level=3", "--edition", "2021", "-o", str(binary),
                            str(source)], check=True)
            return [str(binary)] + args
        if language == "Java":
            classes = BUILD / ("java-" + source.stem)
            classes.mkdir(exist_ok=True)
            subprocess.run(["javac", "-d", str(classes), str(source)], check=True)
            return ["java", "-cp", str(classes), source.stem] + args
        raise ValueError(language)


EXTENSIONS = {"Unio": ".unio", "Unio native": ".unio", "Python": ".py", "Ruby": ".rb", "JavaScript": ".js", "Go": ".go",
              "Java": ".java", "Rust": ".rs"}
ORDER = ["Unio", "Unio native", "Python", "Ruby", "JavaScript", "Go", "Java", "Rust"]


def programs(name, languages):
    """(language, variant, source): 'same' is the algorithm of the Unio program; 'built-in' is
    the language's own library for the task, where the benchmark has one (JSON)."""
    directory = BENCH / name
    found = []
    for language in ORDER:
        if language == "Unio native" and not languages.native:
            continue
        for path in sorted(directory.iterdir()):
            if path.suffix != EXTENSIONS[language]:
                continue
            variant = "built-in" if "builtin" in path.stem.lower() else "same"
            found.append((language, variant, path))
    return found


_LAUNCHER = []


def launcher():
    """bench/build/peak_rss, built once from bench/peak_rss.c; None without a C compiler or
    on Windows, and then memory is not measured."""
    if not _LAUNCHER:
        binary = BUILD / "peak_rss"
        compiler = shutil.which("cc")
        if os.name == "posix" and compiler:
            BUILD.mkdir(exist_ok=True)
            done = subprocess.run([compiler, "-O2", "-o", str(binary), str(BENCH / "peak_rss.c")])
            _LAUNCHER.append(str(binary) if done.returncode == 0 else None)
        else:
            _LAUNCHER.append(None)
    return _LAUNCHER[0]


def run_once(command, cwd, own_clock=False):
    """Runs the command; returns (exit code, stdout, stderr, wall seconds, peak RSS in bytes).

    The launcher adds well under a millisecond to the wall time; without it the peak is None.
    With `own_clock`, the time is the launcher's, from its fork to the end of the child, which
    leaves out the start of the launcher by Python (for the start-up benchmark)."""
    tool = launcher()
    start = time.perf_counter()
    done = subprocess.run(([tool] if tool else []) + command, capture_output=True, cwd=cwd)
    elapsed = time.perf_counter() - start
    stderr = done.stderr.decode("utf-8", "replace")
    peak = None
    if tool:
        head, _, last = stderr.rstrip("\n").rpartition("\n")
        if last.startswith("peak_rss "):
            fields = last.split()
            peak = int(fields[1])
            if own_clock and len(fields) > 2:
                elapsed = int(fields[2]) / 1e9
            stderr = head
    return done.returncode, done.stdout.decode("utf-8", "replace"), stderr, elapsed, peak


def measure(command, runs, cwd, memory=None, samples=None, own_clock=False):
    """Best wall time of the runs and the output; the peak RSS of each run goes into `memory`
    and the time of each run into `samples`, so that the median and the spread are recorded."""
    best = None
    output = None
    for _ in range(runs):
        code, stdout, stderr, elapsed, peak = run_once(command, cwd, own_clock)
        if code != 0:
            return None, (stderr.strip().splitlines() or ["exit " + str(code)])[-1]
        output = stdout.strip()
        best = elapsed if best is None else min(best, elapsed)
        if samples is not None:
            samples.append(elapsed)
        if memory is not None and peak is not None:
            memory.append(peak)
    return best, output


def reference(languages):
    """The Unio column that ratios and the floor refer to."""
    return "Unio native" if languages.native else "Unio"


def tool_rows(languages, runs):
    """(e): the project tools of tools/ in Unio against the Python checkers of spec/."""
    sources = sorted(
        [str(p.relative_to(ROOT)) for p in (ROOT / "docs" / "examples").glob("*.unio")]
        + [str(p.relative_to(ROOT)) for p in (ROOT / "docs" / "ru" / "examples").glob("*.unio")]
        + [str(p.relative_to(ROOT)) for p in (ROOT / "examples").glob("*.unio")]
        + [str(p.relative_to(ROOT)) for p in (ROOT / "stdlib").rglob("*.unio")]
        + [str(p.relative_to(ROOT)) for p in (ROOT / "tools").glob("*.unio")]
    )
    pairs = [
        ("check_grammar (all sources)", ["tools/check_grammar.unio", "--"] + sources,
         ["spec/check_grammar.py"] + sources),
        ("check_grammar --corpus", ["tools/check_grammar.unio", "--", "--corpus"],
         ["spec/check_grammar.py", "--corpus"]),
        ("check_api", ["tools/check_api.unio"], ["spec/check_api.py"]),
        ("check_docs", ["tools/check_docs.unio"], [".github/scripts/check_docs.py"]),
    ]
    rows = []
    for name, unio_args, python_args in pairs:
        row = {"benchmark": "tools", "case": name, "times": {}, "notes": {}}
        if languages.unio:
            t, out = measure([languages.unio, "run"] + unio_args, runs, ROOT)
            row["times"]["Unio"] = t
            if t is None:
                row["notes"]["Unio"] = out
        if languages.native and languages.unio:
            BUILD.mkdir(exist_ok=True)
            source = ROOT / unio_args[0]
            binary = BUILD / (source.stem + "-unio")
            subprocess.run([languages.unio, "build", "--release", str(source), "-o", str(binary)],
                           check=True)
            t, out = measure([str(binary)] + unio_args[2:], runs, ROOT)
            row["times"]["Unio native"] = t
            if t is None:
                row["notes"]["Unio native"] = out
        t, out = measure([languages.python] + python_args, runs, ROOT)
        row["times"]["Python"] = t
        if t is None:
            row["notes"]["Python"] = out
        rows.append(row)
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--runs", type=int, default=3, help="best of N runs (default 3)")
    parser.add_argument("--only", default="wc,json,text,loop,empty,tools,free,package,copies",
                        help="benchmarks to run")
    parser.add_argument("--json", default=str(BENCH / "results.json"), help="where to write JSON")
    parser.add_argument("--check-floor", action="store_true",
                        help="exit 1 if Unio is slower than 0.5x Python on wc, json, text, loop")
    parser.add_argument("--check-go", action="store_true",
                        help="exit 1 if Unio is above the time or memory limits against Go of RFC 0003")
    parser.add_argument("--check-startup", action="store_true",
                        help="exit 1 if the native executable of an empty program starts in more than 5 ms"
                             " (median of the runs of the benchmark empty; needs --native)")
    parser.add_argument("--check-free", action="store_true",
                        help="exit 1 if freeing the wide heap of the benchmark free takes more than"
                             " 1 ms per MB of peak memory (median; RFC 0007)")
    parser.add_argument("--check-compile", action="store_true",
                        help="exit 1 if unio check of the 10,000-line package takes more than 1 s or"
                             " a full unio build --release of it more than 30 s (median; 7.1)")
    parser.add_argument("--check-copies", action="store_true",
                        help="exit 1 if a change in place or of one level costs more at ten times the"
                             " size (L-11b)")
    parser.add_argument("--unio", default=None, help="path to the unio binary")
    parser.add_argument("--native", action="store_true",
                        help="also build the Unio programs with unio build --release and compare those")
    options = parser.parse_args()
    selected = options.only.split(",")

    unio = find_unio(options.unio)
    languages = Languages(unio, options.native)
    data = ensure_data()

    print("Versions:")
    for language in ORDER:
        if language in languages.versions and languages.versions[language]:
            print(f"  {language:<11} {languages.versions[language]}")
        else:
            print(f"  {language:<11} skipped: {languages.missing.get(language, 'not found')}")
    print(f"  {'Machine':<11} {platform.platform()}, {os.cpu_count()} CPUs")
    print(f"Best of {options.runs} runs, wall time of the whole process.\n")

    rows = []
    failures = []
    for name in ("wc", "json", "text", "loop"):
        if name not in selected:
            continue
        outputs = {}
        for language, variant, source in programs(name, languages):
            row_case = "same algorithm" if variant == "same" else "built-in library"
            row = next((r for r in rows if r["benchmark"] == name and r["case"] == row_case), None)
            if row is None:
                row = {"benchmark": name, "case": row_case, "times": {}, "notes": {}}
                rows.append(row)
            if language in languages.missing:
                row["notes"][language] = "skipped: " + languages.missing[language]
                continue
            try:
                command = languages.command(language, source, data.get(name))
            except subprocess.CalledProcessError as e:
                row["notes"][language] = f"build failed: {e}"
                failures.append(f"{name}/{language}: build failed")
                continue
            peaks, samples = [], []
            t, out = measure(command, options.runs, ROOT, peaks, samples)
            if peaks:
                row.setdefault("memory", {})[language] = min(peaks)
            if samples:
                row.setdefault("runs", {})[language] = {
                    "times": samples,
                    "median": statistics.median(samples),
                    "spread": max(samples) - min(samples),
                }
            if t is None:
                row["notes"][language] = "failed: " + out
                failures.append(f"{name}/{language}: {out}")
                continue
            row["times"][language] = t
            outputs[f"{language} ({variant})"] = out
            print(f"  {name:<5} {row_case:<17} {language:<11} {t:8.3f} s  -> {out}", file=sys.stderr)
        if len(set(outputs.values())) > 1:
            failures.append(f"{name}: outputs differ: {outputs}")
        for row in rows:
            if row["benchmark"] == name:
                row["output"] = next(iter(outputs.values()), None)
        if name == "json":
            for row in rows:
                if row["benchmark"] == name and row["case"] == "built-in library":
                    for language in ("Java", "Rust"):
                        row["notes"].setdefault(language, "no JSON in the standard library")
    startup_failures = []
    if "empty" in selected:
        rows.append(startup_row(languages, startup_failures, failures))
    if "tools" in selected:
        rows.extend(tool_rows(languages, options.runs))
    free_failures = []
    free = free_rows(languages, free_failures, failures) if "free" in selected else []
    compile_failures = []
    package = package_rows(languages, compile_failures, failures) if "package" in selected else []
    copy_failures = []
    copies = copy_rows(languages, copy_failures, failures) if "copies" in selected else []

    print_table(rows, reference(languages))
    if "empty" in selected:
        print_startup(next(r for r in rows if r["benchmark"] == "empty"))

    floor_failures = []
    for row in rows:
        if row["benchmark"] in FLOOR_BENCHMARKS and row["case"] == "same algorithm":
            ref = reference(languages)
            u, p = row["times"].get(ref), row["times"].get("Python")
            if u is None or p is None:
                floor_failures.append(f"{row['benchmark']}: no time for {ref} or Python")
            elif p / u < FLOOR:
                floor_failures.append(f"{row['benchmark']}: {ref} {u:.3f} s is {p / u:.2f}x Python {p:.3f} s")

    go_failures = []
    print(f"\n{reference(languages)} against Go (RFC 0003: time at most {GO_LIMIT}x, target 1x; peak memory"
          f" at most {GO_LIMIT}x + 8 MB; gated: {', '.join(GO_GATED)}):")
    for row in rows:
        if row["benchmark"] in FLOOR_BENCHMARKS and row["case"] == "same algorithm":
            ref = reference(languages)
            u, g = row["times"].get(ref), row["times"].get("Go")
            gated = row["benchmark"] in GO_GATED
            if u is None or g is None:
                print(f"  {row['benchmark']:<5} not measured: no time for {ref} or Go")
                if gated:
                    go_failures.append(f"{row['benchmark']}: no time for {ref} or Go")
                continue
            memory = row.get("memory", {})
            um, gm = memory.get(ref), memory.get("Go")
            memory_text = ""
            if um is not None and gm is not None:
                limit = GO_LIMIT * gm + GO_MEMORY_ALLOWANCE
                memory_text = f"   memory {um / gm:5.2f}x Go ({um / 1e6:.1f} of at most {limit / 1e6:.1f} MB)"
                if gated and um > limit:
                    go_failures.append(f"{row['benchmark']}: {ref} peak {um / 1e6:.1f} MB is above"
                                       f" {limit / 1e6:.1f} MB (2x Go {gm / 1e6:.1f} MB + 8 MB)")
            elif gated:
                go_failures.append(f"{row['benchmark']}: no peak memory for {ref} or Go")
            print(f"  {row['benchmark']:<5} time {u / g:5.2f}x Go{memory_text}{'  (gated)' if gated else ''}")
            if gated and u / g > GO_LIMIT:
                go_failures.append(f"{row['benchmark']}: {ref} {u:.3f} s is {u / g:.2f}x Go {g:.3f} s")
    for name in GO_GATED:
        if not any(r["benchmark"] == name and r["case"] == "same algorithm" for r in rows):
            go_failures.append(f"{name}: gated by RFC 0003 but not run")
    print_memory(rows)
    if free:
        print_free(free)
    if package:
        print_package(package)
    if copies:
        print_copies(copies)

    report = {
        "versions": languages.versions,
        "skipped": languages.missing,
        "machine": platform.platform(),
        "runs": options.runs,
        "floor": FLOOR,
        "rows": rows,
        "failures": failures,
        "floor_failures": floor_failures,
        "go_limit": GO_LIMIT,
        "go_gated": list(GO_GATED),
        "go_failures": go_failures,
        "startup_limit": STARTUP_LIMIT,
        "startup_failures": startup_failures,
        "free": free,
        "free_limit": FREE_LIMIT,
        "free_limit_per_mb": FREE_LIMIT_PER_MB,
        "free_failures": free_failures,
        "package": package,
        "check_limit": CHECK_LIMIT,
        "build_limit": BUILD_LIMIT,
        "compile_failures": compile_failures,
        "copies": copies,
        "copy_growth_limit": COPY_GROWTH_LIMIT,
        "copy_failures": copy_failures,
    }
    Path(options.json).write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"\nJSON written to {options.json}")
    for failure in failures:
        print("error: " + failure, file=sys.stderr)
    for failure in floor_failures:
        print(f"{'error' if options.check_floor else 'note'}: below the {FLOOR}x floor of 7.1: {failure}",
              file=sys.stderr)
    for failure in go_failures:
        print(f"{'error' if options.check_go else 'note'}: against Go (RFC 0003): {failure}",
              file=sys.stderr)
    if options.check_startup and not languages.native:
        startup_failures.append("--check-startup needs --native")
    if options.check_startup and "empty" not in selected:
        startup_failures.append("--check-startup needs the benchmark empty")
    for failure in startup_failures:
        print(f"{'error' if options.check_startup else 'note'}: start-up (7.1): {failure}", file=sys.stderr)
    if options.check_free and "free" not in selected:
        free_failures.append("--check-free needs the benchmark free")
    for failure in free_failures:
        print(f"{'error' if options.check_free else 'note'}: freeing (RFC 0007): {failure}", file=sys.stderr)
    if options.check_compile and "package" not in selected:
        compile_failures.append("--check-compile needs the benchmark package")
    for failure in compile_failures:
        print(f"{'error' if options.check_compile else 'note'}: compile time (7.1): {failure}", file=sys.stderr)
    if options.check_copies and "copies" not in selected:
        copy_failures.append("--check-copies needs the benchmark copies")
    for failure in copy_failures:
        print(f"{'error' if options.check_copies else 'note'}: copies (L-11b): {failure}", file=sys.stderr)
    if (failures or (options.check_floor and floor_failures) or (options.check_go and go_failures)
            or (options.check_startup and startup_failures) or (options.check_free and free_failures)
            or (options.check_compile and compile_failures) or (options.check_copies and copy_failures)):
        return 1
    return 0


def startup_row(languages, startup_failures, failures):
    """(f): the start of an empty program in each language, the median of STARTUP_RUNS runs by
    the launcher's clock; the limit of 7.1 applies to the native executable."""
    row = {"benchmark": "empty", "case": "start-up (median)", "times": {}, "notes": {}}
    for language, _, source in programs("empty", languages):
        if language in languages.missing:
            row["notes"][language] = "skipped: " + languages.missing[language]
            continue
        try:
            command = languages.command(language, source, None)
        except subprocess.CalledProcessError as e:
            row["notes"][language] = f"build failed: {e}"
            failures.append(f"empty/{language}: build failed")
            continue
        peaks, samples = [], []
        t, out = measure(command, STARTUP_RUNS, ROOT, peaks, samples, own_clock=True)
        if t is None:
            row["notes"][language] = "failed: " + out
            failures.append(f"empty/{language}: {out}")
            continue
        median = statistics.median(samples)
        row["times"][language] = median
        row.setdefault("runs", {})[language] = {
            "times": samples,
            "best": t,
            "median": median,
            "spread": max(samples) - min(samples),
        }
        if peaks:
            row.setdefault("memory", {})[language] = min(peaks)
        print(f"  empty start-up {language:<11} median {median * 1000:6.2f} ms, best {t * 1000:6.2f} ms"
              f" of {STARTUP_RUNS} runs", file=sys.stderr)
    native = row["times"].get("Unio native")
    if languages.native:
        if native is None:
            startup_failures.append("no time for Unio native")
        elif native > STARTUP_LIMIT:
            startup_failures.append(f"Unio native starts in {native * 1000:.2f} ms (median), above"
                                    f" {STARTUP_LIMIT * 1000:.0f} ms")
    return row


def free_once(command, cwd):
    """Runs the program of bench/free/; returns (pause in seconds, peak RSS in bytes or None),
    or (None, message). The pause is the time between the line printed before the drop and the
    line printed after it, read from a pipe as they arrive; the language has no clock."""
    tool = launcher()
    process = subprocess.Popen(([tool] if tool else []) + command, cwd=cwd,
                               stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    built = process.stdout.readline()
    before = time.perf_counter()
    freed = process.stdout.readline()
    after = time.perf_counter()
    _, stderr = process.communicate()
    stderr = stderr.decode("utf-8", "replace")
    if process.returncode != 0 or not built.startswith(b"built") or freed.strip() != b"freed":
        return None, (stderr.strip().splitlines() or ["exit " + str(process.returncode)])[-1]
    peak = None
    last = stderr.rstrip("\n").rpartition("\n")[2]
    if last.startswith("peak_rss "):
        peak = int(last.split()[1])
    return after - before, peak


def free_rows(languages, free_failures, failures):
    """(g): the pause of freeing a large structure at once, in the interpreter and natively."""
    source = BENCH / "free" / "free.unio"
    rows = []
    for language in ("Unio", "Unio native"):
        if language in languages.missing or (language == "Unio native" and not languages.native):
            continue
        try:
            command = languages.command(language, source, None)
        except subprocess.CalledProcessError as e:
            failures.append(f"free/{language}: build failed: {e}")
            continue
        for case, size in FREE_CASES:
            pauses, peaks = [], []
            for _ in range(FREE_RUNS):
                pause, peak = free_once(command + ([] if language == "Unio native" else ["--"])
                                        + [case, str(size)], ROOT)
                if pause is None:
                    failures.append(f"free/{language}/{case}: {peak}")
                    break
                pauses.append(pause)
                if peak is not None:
                    peaks.append(peak)
            if not pauses:
                continue
            row = {"language": language, "case": case, "size": size, "pauses": pauses,
                   "median": statistics.median(pauses), "worst": max(pauses),
                   "peak": min(peaks) if peaks else None}
            rows.append(row)
            print(f"  free {case:<4} {language:<11} median {row['median'] * 1000:8.2f} ms,"
                  f" worst {row['worst'] * 1000:8.2f} ms of {FREE_RUNS} runs", file=sys.stderr)
            if case == "wide" and row["peak"]:
                limit = FREE_LIMIT_PER_MB * row["peak"] / 1e6
                if row["median"] > limit:
                    free_failures.append(f"{language} frees {row['peak'] / 1e6:.0f} MB in"
                                         f" {row['median'] * 1000:.1f} ms, above {limit * 1000:.1f} ms")
    return rows


def package_rows(languages, compile_failures, failures):
    """(i): `unio check` and a full `unio build --release` of the generated 10,000-line package
    (7.1), the median and the best of PACKAGE_RUNS runs each, with the peak memory. The
    executable built must print what `unio run` prints."""
    if languages.unio is None:
        compile_failures.append("no unio to measure")
        return []
    sys.path.insert(0, str(BENCH / "package"))
    import generate
    directory = DATA / "package"
    modules, lines, non_blank = generate.generate(directory, PACKAGE_LINES)
    print(f"  package: {modules} modules, {lines} lines ({non_blank} not blank)", file=sys.stderr)
    binary = BUILD / "package-unio"
    BUILD.mkdir(exist_ok=True)
    commands = (
        ("check", [languages.unio, "check", "main.unio"], CHECK_LIMIT),
        ("build --release", [languages.unio, "build", "--release", "main.unio", "-o", str(binary)],
         BUILD_LIMIT),
    )
    rows = []
    for name, command, limit in commands:
        samples, peaks = [], []
        for _ in range(PACKAGE_RUNS):
            shutil.rmtree(directory / "target", ignore_errors=True)
            code, _, stderr, elapsed, peak = run_once(command, directory)
            if code != 0:
                failures.append(f"package/{name}: " + (stderr.strip().splitlines() or ["exit " + str(code)])[-1])
                break
            samples.append(elapsed)
            if peak is not None:
                peaks.append(peak)
        if not samples:
            compile_failures.append(f"unio {name}: failed")
            continue
        row = {"command": "unio " + name, "modules": modules, "lines": lines, "non_blank": non_blank,
               "times": samples, "median": statistics.median(samples), "best": min(samples),
               "peak": min(peaks) if peaks else None, "limit": limit}
        rows.append(row)
        print(f"  package unio {name:<15} median {row['median']:7.3f} s, best {row['best']:7.3f} s"
              f" of {len(samples)} runs", file=sys.stderr)
        if row["median"] > limit:
            compile_failures.append(f"unio {name} of {non_blank} lines takes {row['median']:.3f} s"
                                    f" (median), above {limit:.0f} s")
    if any(r["command"] == "unio build --release" for r in rows):
        interpreted = run_once([languages.unio, "run", "main.unio"], directory)
        native = run_once([str(binary)], directory)
        if interpreted[0] != 0 or native[0] != 0 or interpreted[1] != native[1]:
            failures.append(f"package: the executable printed {native[1].strip()!r} (exit {native[0]}),"
                            f" unio run {interpreted[1].strip()!r} (exit {interpreted[0]})")
    return rows


