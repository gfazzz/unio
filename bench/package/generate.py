#!/usr/bin/env python3
"""Generate the package of the compile-time benchmark of requirement 7.1 (bench/README.md).

Usage:
    python3 bench/package/generate.py DIR [--lines N]

Writes a Unio package of at least N lines that are not blank (default 10,000) into DIR: a manifest, shared
interfaces, errors and generic types in `shared/`, a model module and a service module per
unit in `model/` and `service/`, and `main.unio`. Each unit declares enums, structs, errors,
implementations of a shared interface, and functions that fail and handle errors; each service
imports its own model, the model and the service of the previous unit, and the shared modules,
so that the imports form a chain across the package. Units differ in their constants, so no two
modules have the same text. Only the Python standard library is used, and the output depends
only on N.
"""

